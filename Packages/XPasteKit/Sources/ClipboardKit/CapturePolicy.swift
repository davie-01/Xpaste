import Foundation

/// 入库前的过滤规则。必须在读取 payload 和任何派生处理之前判定。
public struct CapturePolicy: Sendable, Equatable {
    public enum SkipReason: Sendable, Equatable {
        case ownWrite, confidential, transient, ignoredApp
    }

    public enum Decision: Sendable, Equatable {
        case capture
        case skip(SkipReason)
    }

    /// 回放时写入的自身标记，采集器据此跳过自己写回的内容。
    public static let selfMarker = "com.mars.XPaste.source"

    // nspasteboard.org 约定的标记及常见旧式标记；它们是应用间约定，不是系统保证。
    static let confidentialMarkers: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "com.agilebits.onepassword",
    ]
    static let transientMarkers: Set<String> = [
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
    ]

    /// 只读取这些表示；WebArchive、dyn.* 和应用私有格式一律不碰。
    /// flat-rtfd 带着网页正文里的图片，卡片和预览按它显示图片（原版如此）。
    public static let allowedTypes: [String] = [
        ClipType.plainText, ClipType.rtf, ClipType.flatRTFD, ClipType.html,
        ClipType.url, ClipType.fileURL, ClipType.png, ClipType.tiff,
    ]

    public var ignoreConfidential = true
    public var ignoreTransient = true
    public var ignoredBundleIDs: Set<String> = []

    public init() {}

    /// `types` 需同时包含 pasteboard 级和每个 item 级的类型：任一处出现标记都整次丢弃。
    public func decide(types: Set<String>, sourceBundleID: String?) -> Decision {
        if types.contains(Self.selfMarker) { return .skip(.ownWrite) }
        if ignoreConfidential, !types.isDisjoint(with: Self.confidentialMarkers) { return .skip(.confidential) }
        if ignoreTransient, !types.isDisjoint(with: Self.transientMarkers) { return .skip(.transient) }
        if let sourceBundleID, ignoredBundleIDs.contains(sourceBundleID) { return .skip(.ignoredApp) }
        return .capture
    }
}
